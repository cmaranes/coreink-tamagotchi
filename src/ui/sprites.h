//   '#' = ink        '.' = paper
//   'e' = eye        (open: drawn; closed: only the bottom row of each eye)
//   'm' = smile pixel (drawn when happy/neutral)
//   'n' = frown pixel (drawn when sad/sick)
//   ',' = paper even over ink (outfits cover the sprite underneath)
// Edit freely - the unit tests check every row has the right width.
